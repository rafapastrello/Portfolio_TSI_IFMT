// Tipos de dados em JavaScript são usados para armazenar e manipular diferentes tipos de informações. Aqui estão alguns dos tipos de dados mais comuns em JavaScript:

let texto = "Olá, mundo!";         // string
let numero = 42;                   // number
let decimal = 3.14;                // number (JS não separe inteiro e decimal)
let booleano = true;               // boolean
let verdadeiro = true;             // boolean
let falso = false;                 // boolean
let nulo = null;                   // null (ausência intencional de valor)
let vazio = null;                  // null
let indefinido;                    // undefined (variável declarada, mas sem valor atribuído)

console.log(typeof texto);         // "string"
console.log(typeof numero);        // "number"
console.log(typeof decimal);       // "number"
console.log(typeof booleano);      // "boolean"
console.log(typeof verdadeiro);    // "boolean"
console.log(typeof falso);         // "boolean"
console.log(typeof nulo);          // "object" 
console.log(typeof vazio);         // "object" (peculiaridade do JS!)
console.log(typeof indefinido);    // "undefined"
