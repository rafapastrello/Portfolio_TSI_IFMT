// Operadores aritméticos em JavaScript são usados para realizar operações matemáticas. Aqui estão alguns exemplos de operadores aritméticos:

let a = 10;
let b = 3;

console.log("Soma: " + (a + b));              // 13
console.log("Subtração: " + (a - b));         // 7
console.log("Multiplicação: " + (a * b));     // 30
console.log("Divisão: " + (a / b));           // 3.3333333333333335
console.log("Resto: " + (a % b));             // 1
console.log("Exponenciação: " + (a ** b));    // 1000
console.log("Incremento: " + (++a));          // 11



// Atalhos de atribuição
let x = 5;

x += 3;     // x = x + 3
x -= 2;     // x = x - 2
x *= 4;     // x = x * 4
x /= 2;     // x = x / 2
x %= 3;     // x = x % 3
x **= 2;    // x = x ** 2
x ++;       // x = x + 1
x --;       // x = x - 1 
